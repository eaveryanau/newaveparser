<?php

namespace App\Normalizer;

use App\DTO\Item;

/**
 * Интерфейс для нормализаторов, преобразующих сырые данные из API в универсальный объект Item.
 *
 * Каждый нормализатор отвечает за конкретный источник данных (например, av.by, mysite)
 * и должен уметь преобразовывать сырой массив в объект Item, а также сообщать,
 * поддерживает ли он данный источник.
 */
interface ItemNormalizerInterface
{
    /**
     * Преобразует сырые данные (ассоциативный массив) из API в объект Item.
     *
     * Метод должен извлекать из массива все необходимые поля:
     *   - id, title, description, price, currency, url, imageUrl, source, raw
     * и заполнять объект Item.
     *
     * @param array $raw Ассоциативный массив с данными элемента, полученными от API.
     *                   Структура зависит от источника и определяется в конкретном нормализаторе.
     *
     * @return Item Готовый объект Item с заполненными свойствами.
     */
    public function normalize(array $raw): Item;

    /**
     * Проверяет, поддерживает ли нормализатор указанный источник данных.
     *
     * Это позволяет команде выбрать подходящий нормализатор на основе значения
     * опции --source, переданной пользователем.
     *
     * @param string $source Идентификатор источника (например, 'avby', 'mysite').
     *                       Должен совпадать со значением, возвращаемым клиентом ApiClientInterface::getSource().
     *
     * @return bool true, если нормализатор может обработать данные из этого источника;
     *              false в противном случае.
     */
    public function supports(string $source): bool;
}
